_NUM = r"(\d+(?:[.,]\d+)?)"
_CUR = r"(?:₽|р\b|р\.|руб\w*|rub|рублей|т\.?\s?р\.?|тр\b|тыс\w*\.?|к\b)"
_WORD_HOURS = {
    "пару часов": 2, "пара часов": 2, "пару-тройку часов": 3, "час-полтора": 1.5, "полтора часа": 1.5,
    "часик": 1, "один час": 1, "два часа": 2, "три часа": 3, "четыре часа": 4, "пять часов": 5,
    "шесть часов": 6, "семь часов": 7, "восемь часов": 8, "десять часов": 10, "двенадцать часов": 12,
    "полдня": 5, "пол дня": 5, "полдень": None, "весь день": 9, "целый день": 9, "сутки": 24,
}


def _to_rub(num: str, cur: str) -> int | None:
    try:
        v = float(num.replace(",", "."))
    except ValueError:
        return None
    c = (cur or "").strip().lower()
    if c.startswith(("т", "к")) and v < 1000:   # 2к, 2.5т.р., 3 тыс
        v *= 1000
    if v < 50 or v > 500000:
        return None
    return int(round(v))


@dataclass
class Pay:
    per_hour: int | None = None
    per_hour_max: int | None = None
    total: int | None = None          # за всю работу / за смену / за день
    total_kind: str | None = None     # total | shift | day
    hours: float | None = None
    days: float | None = None         # многодневные поездки
    per_day: int | None = None
    effective_hourly: int | None = None
    confident: bool = False
    note: str = ""


_HOUR_UNIT = r"(?:\s*/\s*ч(?:ас)?\b|\s*в\s*час\b|\s*за\s*час\b|\s*/\s*час\b|\s*р/ч\b|\s*₽/ч\b|\s*руб\.?/ч\b|\s*час\b|\s*ч\b)"
_SHIFT_UNIT = r"(?:\s*(?:за|/|в)\s*смен\w*|\s*смена\b|\s*за\s*выход\b)"
_DAY_UNIT = r"(?:\s*(?:в|за|/)\s*(?:день|сутки)\b)"

_PAT_CUR = re.compile(r"(?<![\d+])(\d+(?:[.,]\d+)?)(?:\s*-\s*(\d+(?:[.,]\d+)?))?\s*(₽|р\b|р\.|руб\w*|rub\b|т\.?\s?р\.?|тр\b|тыс\w*\.?|к\b)")
_PAT_KW = re.compile(
    r"(?:оплата|оплачу|плачу|заплачу|ставка|платим|получишь|получите|вознагражден\w*|з/п|зп)\s*[:\-]?\s*(?:от\s*|по\s*|до\s*)?"
    r"(\d{3,6})(?:\s*-\s*(\d{3,6}))?(?!\s*(?:ч\b|час|человек|чел\b|лет|года|этаж|%|\d|:))")
_PAT_HOURLY_BARE = re.compile(r"(?<![\d+:.])(\d{3,5})(?:\s*-\s*(\d{3,5}))?\s*(?=/\s*ч(?:ас)?\b|в\s*час\b|за\s*час\b)")
_PAT_UNIT_BARE = re.compile(
    r"(?<![\d+:.])(\d{3,6})(?:\s*-\s*(\d{3,6}))?\s*(?=за\s*смен|/\s*смен|в\s*смену|в\s*день|за\s*день|/\s*день|за\s*выход|в\s*сутки|за\s*сутки"
    r"|за\s*(?:всё|все|работу|заказ|рейс|поездку|выезд))")


_NO_TIME_BEFORE = r"(?<![\d:/.,])(?<!в )(?<!к )(?<!до )(?<!с )(?<!после )(?<!на )"


def parse_hours(t: str) -> float | None:
    """Сколько часов длится работа (берём максимум — так почасовая считается честно)."""
    cands: list[float] = []
    # «на 3-4 часа», «2-3ч»
    for m in re.finditer(r"(?<![\d:])(?<!в )(?<!к )(?<!до )(?<!с )(?<!после )" + _NUM + r"\s*(?:-|до)\s*" + _NUM + r"\s*(?:ч\b|час)", t):
        a, b = float(m.group(1).replace(",", ".")), float(m.group(2).replace(",", "."))
        if 0 < a <= 24 and 0 < b <= 24:
            cands.append(max(a, b))
    # «4ч», «3 часа», «на 2 часа», «за 3 часа» (но не «в 18 часов» — это время)
    for m in re.finditer(r"(?<![\d:/.,])(?<!в )(?<!к )(?<!до )(?<!с )(?<!после )" + _NUM + r"\s*(?:ч\b|час(?:а|ов)?\b|часик)", t):
        try:
            v = float(m.group(1).replace(",", "."))
        except ValueError:
            continue
        if 0 < v <= 24:
            cands.append(v)
    # «с 10 до 14», «10:00-14:00», «с 22:00 до 6:00»
    for m in re.finditer(r"(с\s*)?(\d{1,2})(?::(\d{2}))?\s*(?:до|-)\s*(\d{1,2})(?::(\d{2}))?(?!\s*(?:₽|р\b|руб|тыс|к\b|\d|человек|чел\b|лет|года|числ|\.\d|[.,]\d))", t):
        if not (m.group(1) or m.group(3) or m.group(5)):
            continue  # «2-3» без «с» и без минут — это не время
        h1, m1, h2, m2 = int(m.group(2)), int(m.group(3) or 0), int(m.group(4)), int(m.group(5) or 0)
        if h1 > 24 or h2 > 24 or m1 > 59 or m2 > 59:
            continue
        dur = (h2 + m2 / 60) - (h1 + m1 / 60)
        if dur <= 0:
            dur += 24
        if 0.5 <= dur <= 16:
            cands.append(round(dur, 1))
    for phrase, val in _WORD_HOURS.items():
        if val and phrase in t:
            cands.append(float(val))
    if re.search(r"(?<!\d )(?<!\d)\bчас\s+работы|\bна\s+час\b|\bработы\s+на\s+час|\bчас\s+времени", t):
        cands.append(1.0)
    if re.search(r"полчаса\s+работ|на\s+полчаса|работы\s+на\s+полчаса", t):
        cands.append(0.5)
    for m in re.finditer(r"(?:работ\w*\s+(?:на\s+)?|займ[её]т\s+|занимает\s+)(\d{1,3})\s*мин|(\d{1,3})\s*мин\w*\s+работ", t):
        v = float(m.group(1) or m.group(2)) / 60
        if 0 < v <= 3:
            cands.append(round(v, 2))
    m = re.search(r"смен\w*\s*(?:по\s*)?(\d{1,2})\s*(?:ч|час)", t)
    if m:
        cands.append(float(m.group(1)))
    # «часов 5», «часа на 3»
    for m in re.finditer(r"\bчас(?:а|ов)\s*(?:на\s*)?(\d{1,2})\b(?!\s*(?::|₽|р\b|руб|тыс|к\b|\d))", t):
        v = float(m.group(1))
        if 0 < v <= 16:
            cands.append(v)
    return max(cands) if cands else None


_WORD_DAYS = {"двое суток": 2, "трое суток": 3, "сутки": 1, "неделю": 7, "на неделю": 7}


def parse_days(t: str) -> float | None:
    cands = []
    for m in re.finditer(r"(?<![\d:/.,])(\d{1,2})(?:\s*-\s*(\d{1,2}))?\s*(?:дн(?:я|ей)\b|сут(?:ок|ки)\b)", t):
        a = float(m.group(1)); b = float(m.group(2)) if m.group(2) else a
        if 0 < max(a, b) <= 30:
            cands.append(max(a, b))
    for phrase, v in _WORD_DAYS.items():
        if phrase in t and "24 часа" not in t:
            cands.append(float(v))
    return max(cands) if cands else None


def _money_matches(t: str):
    """Все упоминания денег: (start, lo, hi, cur, end)."""
    out = {}
    for pat, has_cur in ((_PAT_CUR, True), (_PAT_KW, False), (_PAT_HOURLY_BARE, False), (_PAT_UNIT_BARE, False)):
        for m in pat.finditer(t):
            st = m.start(1)
            if st in out:
                continue
            ctx_digits = re.sub(r"\D", "", t[max(0, m.start(1) - 4):m.end() + 4])
            if len(ctx_digits) >= 10:          # кусок телефона
                continue
            cur = m.group(3) if has_cur else ""
            lo = _to_rub(m.group(1), cur)
            hi = _to_rub(m.group(2), cur) if m.group(2) else None
            if lo is None:
                continue
            if hi is not None and hi < lo:
                hi = None
            out[st] = (st, lo, hi, cur, m.end())
    return sorted(out.values())


_STREETISH = re.compile(r"(?:ая|яя|ой|ий|ого|ова|ева|ина|ына|ская|кая|ул|д|дом|кв|офис|каб|этаж|№|номер|корпус|стр|пр|пер)\.?$")
_PAT_BARE = re.compile(r"(?<![\d+:./-])(\d{3,5})(?!\d|[.,:/-]\d|\s*-\s*\d)(?!\s*(?:человек|чел\b|лет|года?\b|этаж|шт|штук|кг|км|м\b|метр|мин|ч\b|час|%|-?х\b|-?й\b|г\.|год|руб|р\b|₽))")


def _bare_amounts(t: str) -> list[int]:
    """«…, 2 часа, 3000» — число без значка рубля. Только если похоже на оплату, а не на адрес/год."""
    out = []
    for m in _PAT_BARE.finditer(t):
        v = int(m.group(1))
        if not 500 <= v <= 60000 or 2019 <= v <= 2031:
            continue
        prev = t[max(0, m.start() - 20):m.start()].strip().split()
        if prev and _STREETISH.search(prev[-1].strip(",.()")):
            continue
        ctx_digits = re.sub(r"\D", "", t[max(0, m.start() - 4):m.end() + 4])
        if len(ctx_digits) >= 10:
            continue
        out.append(v)
    return out


def parse_pay(t: str) -> Pay:
    p = Pay()
    hourly: list[tuple[int, int]] = []
    totals: list[tuple[int, str]] = []
    matches = _money_matches(t)
    if not matches:
        matches = [(0, v, None, "", 0) for v in _bare_amounts(t)][:1]
        if matches:
            p.note = "сумма без «₽» — проверь"
    for st, lo, hi, cur, end in matches:
        tail = t[end:end + 24] if end else ""
        head = t[max(0, st - 16):st] if end else ""
        if re.match(_HOUR_UNIT, tail) or re.search(r"(?:в|за)\s*час\s*[-:]?\s*$|почасов\w*\s*[-:]?\s*$|/ч\s*$", head):
            if 100 <= lo <= 10000:
                hourly.append((lo, hi or lo))
            continue
        if re.match(_SHIFT_UNIT, tail) or re.search(r"смен\w*\s*[-:]?\s*$", head):
            totals.append((lo, "shift"))
        elif re.match(_DAY_UNIT, tail) or re.search(r"(?:в|за)\s*(?:день|сутки)\s*[-:]?\s*$", head):
            totals.append((lo, "day"))
        elif lo >= 300:
            totals.append((lo, "total"))

    p.hours = parse_hours(t)
    p.days = parse_days(t)
    sleep_ok = re.search(r"можно\s+(?:по)?спать|спальн\w+\s+мест|с\s+возможностью\s+сна", t) is not None
    if hourly:
        lo, hi = min(hourly)
        p.per_hour, p.per_hour_max = lo, (hi if hi != lo else None)
        p.effective_hourly = lo
        p.confident = True
        p.note = f"{lo}–{hi} ₽/ч" if hi != lo else f"{lo} ₽/ч"
        if totals:
            p.total, p.total_kind = max(totals)
        return p
    if totals:
        # главная сумма: смена/день важнее «просто суммы», дальше — максимальная
        totals.sort(key=lambda x: (x[1] != "total", x[0]), reverse=True)
        p.total, p.total_kind = totals[0]
        if p.hours and p.hours > 0 and p.total_kind in ("total", "shift"):
            awake = p.hours / 2 if sleep_ok and p.hours >= 6 else p.hours
            eh = int(round(p.total / awake))
            if 100 <= eh <= 10000:
                p.effective_hourly = eh
                p.confident = True
        if p.total_kind == "day":
            p.per_day = p.total
        elif p.days and p.days >= 1 and p.total_kind == "total" and not p.effective_hourly:
            p.per_day = int(round(p.total / p.days))
        kind_ru = {"shift": "за смену", "day": "в день", "total": ""}[p.total_kind]
        extra = p.note
        p.note = f"{p.total:,} ₽ {kind_ru}".replace(",", " ").strip()
        if sleep_ok:
            p.note += " · можно спать"
        if extra:
            p.note += f" ({extra})"
        if p.hours:
            p.note += f" · {p.hours:g} ч"
        elif p.days and p.total_kind != "day":
            p.note += f" · {p.days:g} дн."
    return p


