def job_profile(t: str) -> tuple[list[tuple[str, str, int]], int | None]:
    """Список найденных видов работ и итоговый уровень «лайтовости» 0..4 (None — не понятно)."""
    t = re.sub(r"@\w+|https?://\S+|t\.me/\S+", " ", t)
    hits = [(k, label, chill) for (k, label, chill, pat) in JOB_TYPES if re.search(pat, t)]
    core = [h for h in hits if h[0] != "event"] or hits
    if not hits:
        level = 1 if re.search(HEAVY_MOD, t) else None
    else:
        keys = {h[0] for h in hits}
        chills = [h[2] for h in hits]
        if "trip" in keys:
            # «сопровождение груза + помочь выгрузить» — всё равно в основном едешь
            level = 4 if not re.search(HEAVY_MOD, t) else 3
        elif keys & {"extras", "research", "sit", "queue"}:
            level = 4 if not keys & {"movers", "labor"} else 2
        else:
            cc = [h[2] for h in core]
            level = int(sum(cc) / len(cc) + 0.5)
            if keys & {"movers", "labor"}:
                level = min(level, 1)
    if level is not None and hits:
        if re.search(LIGHT_MOD, t):
            level = min(4, level + 1)
        if re.search(HEAVY_MOD, t):
            level = max(0, level - 1)
    return hits, level


