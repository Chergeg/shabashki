@dataclass
class Features:
    kind: str
    kind_reason: str | None
    pay: Pay
    jobs: list[tuple[str, str, int]] = field(default_factory=list)
    chill: int | None = None
    trip: bool = False
    interest: list[tuple[str, float]] = field(default_factory=list)
    content: bool = False
    reqs: list[str] = field(default_factory=list)
    urgent: bool = False
    pay_now: bool = False
    permanent: bool = False
    when: str | None = None
    people: int | None = None
    private: bool = False         # частник с бытовой задачей (квартира, переезд, мебель, дача)
    short: bool = False           # работы на час-два


def analyze(text: str) -> Features:
    t = norm(text)
    tc = re.sub(r"@\w+|https?://\S+|t\.me/\S+", " ", t)   # без ников и ссылок — для смысла
    kind, reason = classify_kind(t)
    pay = parse_pay(t)
    if kind in ("offer", "unknown") and any(re.search(p, t) for p in UNPAID_PATTERNS) \
            and not (pay.per_hour or pay.total):
        kind, reason = "unpaid", "без оплаты"
    jobs, chill = job_profile(t)
    trip = is_trip(t)
    if trip:
        chill = max(chill or 0, 2 if re.search(HEAVY_MOD, t) else 3)
    return Features(
        kind=kind,
        kind_reason=reason,
        pay=pay,
        jobs=jobs,
        chill=chill,
        trip=trip,
        interest=interest_hits(tc),
        content=content_match(tc),
        reqs=requirements(t),
        urgent=is_urgent(t),
        pay_now=pays_now(t),
        permanent=is_permanent(t),
        when=when_text(t),
        people=people_needed(t),
        private=bool(re.search(PRIVATE_MARKERS, tc)),
        short=(pay.hours is not None and pay.hours <= 2) or bool(re.search(SHORT_MARKERS, tc)),
    )
