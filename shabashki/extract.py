_SPACES = re.compile(r"[ \t\u00a0\u2009\u202f]+")


def norm(text: str) -> str:
    t = (text or "").lower().replace("ё", "е")
    t = t.replace("\u2013", "-").replace("\u2014", "-").replace("\u2212", "-")
    t = _SPACES.sub(" ", t)
    # телефоны убираем, чтобы их цифры не приняли за деньги (сами номера берём из исходного текста)
    t = re.sub(r"(?:\+7|\b8)[\s\-()]*\d{3}[\s\-()]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}\b", " тел ", t)
    # «2 500» -> «2500», «10 000» -> «10000» (только тысячи)
    t = re.sub(r"(?<![\d.,])(\d{1,3}) (\d{3})(?![\d])", r"\1\2", t)
    return t


def _has(pattern: str, t: str) -> bool:
    return re.search(pattern, t) is not None


